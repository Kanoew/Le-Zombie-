from playwright.sync_api import sync_playwright,expect
from browser_support import install_routes
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 for w,h in [(390,844),(844,390)]:
  page=browser.new_page(viewport={'width':w,'height':h},has_touch=True,is_mobile=True)
  errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  install_routes(page);page.goto('https://prototype.test/Le-Zombie-/')
  expect(page.locator('#asset-status')).to_have_text('Ton équipement est prêt.')
  page.locator('#play').tap();expect(page.locator('#objective')).to_contain_text('Pars explorer')
  page.screenshot(path=f'/tmp/le-zombie-07-refuge-{w}.png')
  page.keyboard.down('ArrowRight')
  expect(page.locator('#interact')).to_contain_text('Explorer le quartier',timeout=10000)
  page.keyboard.up('ArrowRight');page.locator('#interact').tap()
  expect(page.locator('#objective')).to_contain_text('Récupère 4')
  page.locator('#pause').tap();s=page.evaluate('JSON.parse(localStorage.getItem("zombie.save"))')
  s['player'].update(x=368,y=576);s['dog'].update(x=336,y=608)
  page.evaluate('(s)=>localStorage.setItem("zombie.save",JSON.stringify(s))',s)
  page.locator('#load').tap();page.locator('#play').tap();page.locator('#interact').tap()
  expect(page.locator('#objective')).to_contain_text('Rapporte ton butin')
  page.locator('#pause').tap();s=page.evaluate('JSON.parse(localStorage.getItem("zombie.save"))')
  s['player'].update(x=80,y=608);s['dog'].update(x=112,y=624)
  page.evaluate('(s)=>localStorage.setItem("zombie.save",JSON.stringify(s))',s)
  page.locator('#load').tap();page.locator('#play').tap();page.locator('#interact').tap()
  page.locator('#pause').tap();s=page.evaluate('JSON.parse(localStorage.getItem("zombie.save"))')
  s['player'].update(x=464,y=304);s['dog'].update(x=410,y=336)
  page.evaluate('(s)=>localStorage.setItem("zombie.save",JSON.stringify(s))',s)
  page.locator('#load').tap();page.locator('#play').tap();page.locator('#interact').tap()
  expect(page.locator('#objective')).to_contain_text('Aménage le refuge')
  page.locator('#refuge-menu').tap();page.locator('#camp-manage').tap();page.locator('[data-module="bunks"]').tap();page.locator('#camp-close').tap()
  expect(page.locator('#objective')).to_contain_text('Tiens face au raid')
  page.locator('#pause').tap();s=page.evaluate('JSON.parse(localStorage.getItem("zombie.save"))')
  assert s['stock']==14 and s['ammo']==30 and s['journey']['rewarded'],s
  page.locator('#play').tap();page.locator('#arsenal-open').tap();page.locator('[data-weapon-group="ranged"]').tap();page.locator('[data-weapon="pistol"]').tap();page.locator('#arsenal-close').tap()
  expect(page.locator('.attack-label')).to_have_text('Tirer');expect(page.locator('#ammo')).to_have_text('30 cartouches')
  page.locator('#pause').tap();s=page.evaluate('JSON.parse(localStorage.getItem("zombie.save"))')
  s.update(zone='street',ammo=18);s['player'].update(x=960,y=608);s['dog'].update(x=928,y=608)
  for e in s['enemies']:e.update(hp=0,respawnAt=s['time']+1000)
  s['enemies'][0].update(x=1088,y=608,hp=60,respawnAt=None,windup=0,cooldown=0)
  page.evaluate('(s)=>localStorage.setItem("zombie.save",JSON.stringify(s))',s)
  page.locator('#load').tap();page.locator('#play').tap()
  box=page.locator('#attack').bounding_box();cdp=page.context.new_cdp_session(page)
  cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':box['x']+box['width']/2,'y':box['y']+box['height']/2,'id':1}]})
  page.wait_for_timeout(720)
  cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
  page.screenshot(path=f'/tmp/le-zombie-07-pistol-{w}.png')
  page.locator('#pause').tap();s=page.evaluate('JSON.parse(localStorage.getItem("zombie.save"))')
  assert 16<=s['ammo']<=17,s['ammo']
  assert s['enemies'][0]['hp']==60-(18-s['ammo'])*24,s['enemies'][0]
  page.locator('#load').tap();page.locator('#play').tap();page.locator('#pause').tap()
  assert page.evaluate('JSON.parse(localStorage.getItem("zombie.save")).ammo')==s['ammo']
  assert not errors,errors
  print(f'OK 0.7 {w}x{h}: sortie au clavier, objectifs, bonus unique, chien et décor, tir maintenu, dégâts et munitions persistants')
  page.close()
 browser.close()
